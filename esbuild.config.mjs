import esbuild from 'esbuild';
import process from 'process';
import { builtinModules } from 'node:module';
import { readFileSync } from 'node:fs';

const notice = path => readFileSync(new URL(path, import.meta.url), 'utf8').replaceAll('\r\n', '\n').trim();
const banner = `/*!
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
Advanced Mermaid source: https://github.com/indubyagee/advanced-mermaid

Advanced Mermaid
${notice('./LICENSE')}

Bundled Pele and third-party notices
${notice('./node_modules/pele/LICENSE')}
*/
`;

const prod = process.argv[2] === 'production';

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
	],
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: 'main.js',
	minify: prod,
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
